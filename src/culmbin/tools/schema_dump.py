"""Write the schema document out of a book the migrations built.

Nobody types this document. It is generated from a fresh in-memory book, so
it cannot disagree with the migrations, and CI regenerates it and compares,
so it cannot go stale either.

The alternative is a hand written schema document, and a hand written schema
document is wrong within two migrations and then actively misleading, which
is worse than not having one.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from culmbin.store.book import MEMORY, Book
from culmbin.store.migrations import MIGRATIONS, latest_version, migrate
from culmbin.tools.sources import project_root

DOCUMENT = "docs/schema.md"
STAMP = "1970-01-01T00:00:00+00:00"
HEADING = "# The book"


def _table_block(book: Book, table: str) -> list[str]:
    """One table, its columns and its indexes."""
    lines = [f"## {table}", ""]
    rows = book.column_details(table)
    lines.append("| column | type | null | key |")
    lines.append("| --- | --- | --- | --- |")
    for row in rows:
        key = "pk" if row["pk"] else ""
        null = "" if row["notnull"] else "yes"
        lines.append(f"| {row['name']} | {row['type'] or ''} | {null} | {key} |")
    keys = book.foreign_keys(table)
    if keys:
        lines.append("")
        for row in keys:
            lines.append(f"- `{row['from']}` refers to `{row['table']}.{row['to']}`")
    indexes = book.indexes(table)
    if indexes:
        lines.append("")
        for row in indexes:
            columns = ", ".join(book.index_columns(str(row["name"])))
            unique = "unique " if row["unique"] else ""
            lines.append(f"- {unique}index `{row['name']}` on ({columns})")
    lines.append("")
    return lines


def render() -> str:
    """The whole schema document, from a book the migrations just built."""
    lines = [
        HEADING,
        "",
        "Generated by `python -m culmbin.tools.schema_dump`. Do not edit it: CI",
        "regenerates it from the migrations and fails if the two disagree.",
        "",
        f"Schema version {latest_version()}, over {len(MIGRATIONS)} migrations.",
        "",
        "## migrations",
        "",
        "| version | name |",
        "| --- | --- |",
    ]
    for migration in MIGRATIONS:
        lines.append(f"| {migration.version} | {migration.name} |")
    lines.append("")
    with Book.open(MEMORY) as book:
        migrate(book, STAMP)
        for table in book.tables():
            lines.extend(_table_block(book, table))
    return "\n".join(lines).rstrip() + "\n"


def document_path() -> Path:
    """Where the schema document lives."""
    return project_root() / DOCUMENT


def main(argv: list[str] | None = None) -> int:
    """Write the document, or check the one on disk is current."""
    parser = argparse.ArgumentParser(description="write the schema document")
    parser.add_argument("--check", action="store_true", help="say whether it is current")
    arguments = parser.parse_args(argv)
    wanted = render()
    path = document_path()
    if not arguments.check:
        path.write_text(wanted, encoding="utf-8")
        print(f"schema: wrote {DOCUMENT}.")
        return 0
    if not path.exists():
        print(f"schema: {DOCUMENT} is not there. Run the generator.")
        return 1
    if path.read_text(encoding="utf-8") != wanted:
        print(f"schema: {DOCUMENT} is out of date. Run the generator.")
        return 1
    print("schema: the document is current.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
