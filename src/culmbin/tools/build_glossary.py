"""Write the glossary out of the enumerations and the analyte table.

Every word in it is a word the package already knows, so nobody argues with
it. A glossary written by hand is a glossary that says `provisional` means
something the code stopped believing two seasons ago.

The prose against each word is not generated: it is the docstring on the
enumeration, which is where somebody who has just read the code will look
for it anyway.
"""

from __future__ import annotations

import argparse
import inspect
import sys
from enum import StrEnum
from pathlib import Path

from culmbin.model import enums
from culmbin.model.analytes import ANALYTES
from culmbin.model.enums import Material
from culmbin.tools.sources import project_root

DOCUMENT = "docs/glossary.md"
HEADING = "# The words"


def _enumerations() -> list[type[StrEnum]]:
    """Every closed vocabulary in the model, in the order they are written."""
    found = []
    for _, value in inspect.getmembers(enums, inspect.isclass):
        if issubclass(value, StrEnum) and value is not StrEnum:
            found.append(value)
    return sorted(found, key=lambda item: item.__name__)


def render() -> str:
    """The whole glossary, out of the enumerations and the analyte table."""
    lines = [
        HEADING,
        "",
        "Generated by `python -m culmbin.tools.build_glossary`. Do not edit it: CI",
        "regenerates it from the enumerations and fails if the two disagree.",
        "",
    ]
    for enumeration in _enumerations():
        lines.append(f"## {enumeration.__name__}")
        lines.append("")
        doc = inspect.getdoc(enumeration) or ""
        if doc:
            lines.append(doc.splitlines()[0])
            lines.append("")
        lines.append("| stored as | name |")
        lines.append("| --- | --- |")
        for member in enumeration:
            lines.append(f"| `{member.value}` | {member.name.replace('_', ' ').lower()} |")
        lines.append("")
    for material in Material:
        lines.append(f"## what the laboratory measures on {material}")
        lines.append("")
        lines.append("| code | determination | unit | basis | places |")
        lines.append("| --- | --- | --- | --- | --- |")
        for item in ANALYTES.values():
            if item.material is not material:
                continue
            basis = item.basis or ""
            lines.append(
                f"| `{item.code}` | {item.label} | {item.unit} | {basis} | {item.places} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def document_path() -> Path:
    """Where the glossary lives."""
    return project_root() / DOCUMENT


def main(argv: list[str] | None = None) -> int:
    """Write the glossary, or check the one on disk is current."""
    parser = argparse.ArgumentParser(description="write the glossary")
    parser.add_argument("--check", action="store_true", help="say whether it is current")
    arguments = parser.parse_args(argv)
    wanted = render()
    path = document_path()
    if not arguments.check:
        path.write_text(wanted, encoding="utf-8")
        print(f"glossary: wrote {DOCUMENT}.")
        return 0
    if not path.exists() or path.read_text(encoding="utf-8") != wanted:
        print(f"glossary: {DOCUMENT} is out of date. Run the generator.")
        return 1
    print("glossary: the glossary is current.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
