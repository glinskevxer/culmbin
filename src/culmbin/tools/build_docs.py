"""Write the command reference out of the console script itself.

There is one description of each command and it is the docstring on the
function. This walks the click tree and writes them out, so the reference
cannot describe a command that has been renamed and cannot miss one that
has been added.

CI runs it with `--check`, which is what stops it going stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import click

from culmbin.cli.main import cli
from culmbin.tools.check_help import walk
from culmbin.tools.sources import project_root

DOCUMENT = "docs/commands.md"
HEADING = "# The console script"


def _option_rows(command: click.Command) -> list[str]:
    """Every option of a command, as table rows."""
    rows = []
    for parameter in command.params:
        if not isinstance(parameter, click.Option) or parameter.name in {"help", "version"}:
            continue
        flags = ", ".join(f"`{item}`" for item in parameter.opts)
        needed = "yes" if parameter.required else ""
        rows.append(f"| {flags} | {needed} | {(parameter.help or '').strip()} |")
    return rows


def _argument_words(command: click.Command) -> str:
    """The positional arguments, as somebody would type them."""
    words = []
    for parameter in command.params:
        if isinstance(parameter, click.Argument):
            name = (parameter.name or "").upper()
            words.append(f"[{name}]" if not parameter.required else name)
    return " ".join(words)


def render() -> str:
    """The whole command reference, from the click tree."""
    lines = [
        HEADING,
        "",
        "Generated by `python -m culmbin.tools.build_docs`. Do not edit it: CI",
        "regenerates it from the console script and fails if the two disagree.",
        "",
    ]
    for path, command in walk(cli):
        if path == "cli":
            continue
        words = path.replace("cli ", "culmbin ", 1)
        arguments = _argument_words(command)
        lines.append(f"## `{words}{' ' + arguments if arguments else ''}`")
        lines.append("")
        lines.append((command.help or "").strip().splitlines()[0])
        lines.append("")
        rows = _option_rows(command)
        if rows:
            lines.append("| option | required | what it is for |")
            lines.append("| --- | --- | --- |")
            lines.extend(rows)
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def document_path() -> Path:
    """Where the command reference lives."""
    return project_root() / DOCUMENT


def main(argv: list[str] | None = None) -> int:
    """Write the reference, or check the one on disk is current."""
    parser = argparse.ArgumentParser(description="write the command reference")
    parser.add_argument("--check", action="store_true", help="say whether it is current")
    arguments = parser.parse_args(argv)
    wanted = render()
    path = document_path()
    if not arguments.check:
        path.write_text(wanted, encoding="utf-8")
        print(f"commands: wrote {DOCUMENT}.")
        return 0
    if not path.exists() or path.read_text(encoding="utf-8") != wanted:
        print(f"commands: {DOCUMENT} is out of date. Run the generator.")
        return 1
    print("commands: the reference is current.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
